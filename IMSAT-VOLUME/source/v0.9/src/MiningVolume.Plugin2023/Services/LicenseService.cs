using System;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Runtime.Serialization;
using System.Runtime.Serialization.Json;
using Microsoft.Win32;

namespace MiningVolume2023.Services
{
    public enum LicenseState { Trial, Activated, TrialExpired, ClockRollback, InvalidLicense, StorageError }

    public sealed class LicenseStatus
    {
        public LicenseState State { get; internal set; }
        public bool CanCalculate => State == LicenseState.Trial || State == LicenseState.Activated;
        public int DaysRemaining { get; internal set; }
        public string Customer { get; internal set; }
        public string Description { get; internal set; }
    }

    [DataContract]
    internal sealed class TrialLedger
    {
        [DataMember(Order = 1)] public string MachineId { get; set; }
        [DataMember(Order = 2)] public DateTime FirstUseUtc { get; set; }
        [DataMember(Order = 3)] public DateTime LastUseUtc { get; set; }
    }

    /// <summary>
    /// Signed token payload. The admin tool signs the ORIGINAL UTF-8 JSON bytes:
    /// MV2.&lt;base64(JsonBytes)&gt;.&lt;base64(RSA-SHA256-Signature)&gt;.
    /// No secret key lives inside the distributed CAD plugin.
    /// </summary>
    [DataContract]
    public sealed class SignedLicensePayload
    {
        [DataMember(Order = 1)] public string LicenseId { get; set; }
        [DataMember(Order = 2)] public string Customer { get; set; }
        [DataMember(Order = 3)] public string MachineId { get; set; }
        [DataMember(Order = 4)] public string Mode { get; set; }
        [DataMember(Order = 5)] public DateTime NotBeforeUtc { get; set; }
        [DataMember(Order = 6)] public DateTime ExpiresUtc { get; set; }
    }

    internal static class LicenseTrustAnchor
    {
        // Provision the PUBLIC verifier in the signed release build only, using the
        // public.xml generated by the offline IMSAT License Manager.
        // Empty deliberately means no activation can be falsely accepted.
        // Never put the private issuer key into the app or the repository.
        internal const string RsaPublicKeyXml = "";
    }

    /// <summary>
    /// 15 continuous calendar days from first successful use per Windows user.
    /// Stores DPAPI-protected ledger in both LocalAppData and HKCU, rejects clock
    /// rollback, and checks machine-bound RSA-SHA256 tokens.
    ///
    /// Offline trials cannot be made tamper-proof if an attacker erases every local
    /// store and the OS has no centrally trusted clock: this is a release caveat.
    /// </summary>
    public static class LicenseService
    {
        private const string RegistryPath = @"Software\IMSAT\MiningVolume\License";
        private const string RegistryTrialValue = "TrialLedger";
        private const string RegistryActivationValue = "Activation";
        private static readonly byte[] Entropy = Encoding.UTF8.GetBytes("IMSAT.MiningVolume.V2.0.OfflineLicense.v1");
        private static readonly object Sync = new object();

        private static string RootDirectory =>
            Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData),
                "IMSAT", "MiningVolume", "License");
        private static string TrialFile => Path.Combine(RootDirectory, "trial.dat");

        public static string MachineId
        {
            get
            {
                string guid = null;
                try
                {
                    using (var key = Registry.LocalMachine.OpenSubKey(@"SOFTWARE\Microsoft\Cryptography", false))
                        guid = key?.GetValue("MachineGuid") as string;
                }
                catch { }
                if (string.IsNullOrWhiteSpace(guid))
                    guid = Environment.MachineName + "|" + Environment.OSVersion.VersionString;
                using (var sha = SHA256.Create())
                    return BitConverter.ToString(sha.ComputeHash(Encoding.UTF8.GetBytes(
                        "IMSAT-V2|" + guid.Trim().ToUpperInvariant()))).Replace("-", "");
            }
        }

        public static LicenseStatus GetStatus()
        {
            lock (Sync)
            {
                try
                {
                    var key = ReadRegistry(RegistryActivationValue);
                    if (key != null)
                    {
                        try
                        {
                            var license = VerifySignedToken(Encoding.UTF8.GetString(key), DateTime.UtcNow);
                            return new LicenseStatus
                            {
                                State = LicenseState.Activated, DaysRemaining = int.MaxValue,
                                Customer = license.Customer,
                                Description = "Đã kích hoạt: " + license.Customer
                            };
                        }
                        catch (Exception ex)
                        {
                            return new LicenseStatus
                            {
                                State = LicenseState.InvalidLicense,
                                Description = "Key không hợp lệ: " + ex.Message
                            };
                        }
                    }

                    DateTime now = DateTime.UtcNow;
                    byte[] fromFile = File.Exists(TrialFile) ? File.ReadAllBytes(TrialFile) : null;
                    byte[] fromRegistry = ReadRegistry(RegistryTrialValue);
                    var ledgers = new[] { fromFile, fromRegistry }
                        .Where(x => x != null)
                        .Select(ReadProtectedLedger)
                        .ToArray();

                    TrialLedger record;
                    if (ledgers.Length == 0)
                        record = new TrialLedger
                        {
                            MachineId = MachineId,
                            FirstUseUtc = now,
                            LastUseUtc = now
                        };
                    else
                    {
                        if (ledgers.Any(x => x.MachineId != MachineId))
                            return new LicenseStatus { State = LicenseState.StorageError,
                                Description = "Dữ liệu dùng thử không thuộc máy hiện tại." };
                        record = new TrialLedger
                        {
                            MachineId = MachineId,
                            FirstUseUtc = ledgers.Min(x => x.FirstUseUtc),
                            LastUseUtc = ledgers.Max(x => x.LastUseUtc)
                        };
                    }

                    // Allow small Windows clock corrections; large rollback blocks use.
                    if (now < record.LastUseUtc.AddHours(-1))
                        return new LicenseStatus
                        {
                            State = LicenseState.ClockRollback,
                            Description = "Đồng hồ hệ thống lùi quá 1 giờ. Kiểm tra ngày giờ Windows."
                        };

                    record.LastUseUtc = now > record.LastUseUtc ? now : record.LastUseUtc;
                    PersistLedger(record);
                    double left = (record.FirstUseUtc.AddDays(15) - now).TotalDays;
                    if (left <= 0)
                        return new LicenseStatus
                        {
                            State = LicenseState.TrialExpired,
                            DaysRemaining = 0,
                            Description = "Đã hết 15 ngày dùng thử. Nhập key để tiếp tục tính toán."
                        };
                    int days = (int)Math.Ceiling(left);
                    return new LicenseStatus
                    {
                        State = LicenseState.Trial,
                        DaysRemaining = days,
                        Description = "Dùng thử: còn " + days + " ngày (15 ngày liên tục từ lần đầu)."
                    };
                }
                catch (Exception ex)
                {
                    return new LicenseStatus
                    {
                        State = LicenseState.StorageError,
                        Description = "Không xác minh được bản quyền cục bộ: " + ex.Message
                    };
                }
            }
        }

        public static void RequireCalculationAccess()
        {
            var status = GetStatus();
            if (!status.CanCalculate)
                throw new InvalidOperationException(status.Description +
                    Environment.NewLine + "Dữ liệu DWG không bị xóa hoặc khóa.");
        }

        public static string Activate(string signedKey)
        {
            if (string.IsNullOrWhiteSpace(signedKey))
                throw new ArgumentException("Cần nhập mã kích hoạt hoặc nội dung file .mvlic.");
            lock (Sync)
            {
                var license = VerifySignedToken(signedKey.Trim(), DateTime.UtcNow);
                var key = Encoding.UTF8.GetBytes(signedKey.Trim());
                SaveRegistry(RegistryActivationValue, key);
                return "Đã kích hoạt giấy phép " + license.LicenseId + " cho " + license.Customer;
            }
        }

        private static SignedLicensePayload VerifySignedToken(string token, DateTime now)
        {
            if (string.IsNullOrWhiteSpace(LicenseTrustAnchor.RsaPublicKeyXml))
                throw new InvalidOperationException("Chưa cấu hình khóa công khai IMSAT trong bản build. Chưa thể kích hoạt.");
            var parts = token.Split('.');
            if (parts.Length != 3 || parts[0] != "MV2")
                throw new InvalidOperationException("Định dạng key không đúng.");
            byte[] data, signature;
            try
            {
                data = Convert.FromBase64String(parts[1]);
                signature = Convert.FromBase64String(parts[2]);
            }
            catch (FormatException) { throw new InvalidOperationException("Key chứa dữ liệu mã hóa không hợp lệ."); }

            using (var rsa = new RSACryptoServiceProvider())
            {
                rsa.FromXmlString(LicenseTrustAnchor.RsaPublicKeyXml);
                if (!rsa.VerifyData(data, CryptoConfig.MapNameToOID("SHA256"), signature))
                    throw new InvalidOperationException("Chữ ký số giấy phép không hợp lệ.");
            }

            SignedLicensePayload payload;
            using (var memory = new MemoryStream(data))
                payload = (SignedLicensePayload)new DataContractJsonSerializer(typeof(SignedLicensePayload)).ReadObject(memory);
            if (payload == null || string.IsNullOrWhiteSpace(payload.LicenseId) ||
                string.IsNullOrWhiteSpace(payload.Customer) ||
                !string.Equals(payload.MachineId, MachineId, StringComparison.OrdinalIgnoreCase))
                throw new InvalidOperationException("Key không đúng máy hoặc thiếu thông tin.");
            if (payload.Mode != "INTERNAL" && payload.Mode != "UNIT")
                throw new InvalidOperationException("Loại key không phải giấy phép người dùng hợp lệ.");
            if (payload.NotBeforeUtc > now || payload.ExpiresUtc <= now)
                throw new InvalidOperationException("Key chưa hiệu lực hoặc đã hết hạn.");
            return payload;
        }

        private static TrialLedger ReadProtectedLedger(byte[] stored)
        {
            byte[] decrypted = ProtectedData.Unprotect(stored, Entropy, DataProtectionScope.CurrentUser);
            using (var memory = new MemoryStream(decrypted))
            {
                var data = (TrialLedger)new DataContractJsonSerializer(typeof(TrialLedger)).ReadObject(memory);
                if (data == null || data.FirstUseUtc == default(DateTime) ||
                    data.LastUseUtc < data.FirstUseUtc)
                    throw new InvalidDataException("Dữ liệu thử bị hỏng.");
                return data;
            }
        }

        private static void PersistLedger(TrialLedger ledger)
        {
            byte[] json;
            using (var memory = new MemoryStream())
            {
                new DataContractJsonSerializer(typeof(TrialLedger)).WriteObject(memory, ledger);
                json = memory.ToArray();
            }
            byte[] cipher = ProtectedData.Protect(json, Entropy, DataProtectionScope.CurrentUser);
            Directory.CreateDirectory(RootDirectory);
            string tmp = TrialFile + ".tmp";
            File.WriteAllBytes(tmp, cipher);
            if (File.Exists(TrialFile)) File.Replace(tmp, TrialFile, null);
            else File.Move(tmp, TrialFile);
            SaveRegistry(RegistryTrialValue, cipher);
        }

        private static byte[] ReadRegistry(string value)
        {
            using (var key = Registry.CurrentUser.OpenSubKey(RegistryPath, false))
                return key?.GetValue(value) as byte[];
        }

        private static void SaveRegistry(string name, byte[] data)
        {
            using (var key = Registry.CurrentUser.CreateSubKey(RegistryPath))
                key.SetValue(name, data, RegistryValueKind.Binary);
        }
    }
}
